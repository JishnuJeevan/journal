import fs from 'node:fs';
import { stepFile } from '../lib/paths.js';
import { loadIndex, getFeature } from '../lib/index-store.js';
import { readStepFile, writeStepFile } from '../lib/frontmatter.js';
import { draftLogic as aiDraftLogic } from '../lib/ai.js';

const DRAFT_BANNER = `> **AI DRAFT — not yet reviewed.** This was generated by \`ledger draft-logic\` as a
> starting point only. Read it critically, correct it, and rewrite it in your own words
> before running \`ledger commit-logic\`. Understanding this is the point of the Logic step —
> not approving text that sounds plausible.

`;

export async function draftLogic(feature, brainDump) {
  const index = loadIndex();
  const entry = getFeature(index, feature);

  if (!entry.steps || !entry.steps.includes('logic')) {
    throw new Error(
      `Feature "${feature}" has no "logic" step in its pipeline (steps: ${entry.steps ? entry.steps.join(', ') : 'none locked yet'}).`
    );
  }

  const file = stepFile(feature, 'logic');
  if (!fs.existsSync(file)) {
    throw new Error(`${file} does not exist. Run \`ledger list-steps ${feature}\` first.`);
  }

  const parsed = readStepFile(file);
  if (parsed.data.attribution) {
    throw new Error(
      `${file} already has attribution "${parsed.data.attribution}" recorded — refusing to ` +
        `overwrite content that's already been committed to. Run \`ledger new-column ${feature}\` ` +
        `to start a fresh revision if you want a new draft.`
    );
  }

  console.log(
    brainDump && brainDump.trim()
      ? `Asking Claude to organize your brain dump into a "${feature}" logic draft...\n`
      : `Asking Claude to draft a starting point for "${feature}" logic...\n`
  );
  const draft = await aiDraftLogic(feature, entry.description, brainDump);

  writeStepFile(file, parsed.data, DRAFT_BANNER + draft + '\n');

  console.log(`Draft written to ${file}`);
  console.log(`Read it, edit it into your own understanding, then run: ledger commit-logic ${feature}`);
}
